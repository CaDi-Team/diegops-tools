use super::*;

#[test]
fn registry_parses_and_expands() {
    let y = r#"
repo:
  path: $HOME/agents-state
  branch: main
heartbeat_kv: me/agents/heartbeat#url
agents:
  - kind: hermes
    root: $HOME/.hermes
    secrets_path: me/agents/hermes
    secrets_backend: openbao
  - kind: pi
"#;
    let r = Registry::parse(y).expect("parse");
    assert_eq!(r.repo.branch.as_deref(), Some("main"));
    assert_eq!(r.agents.len(), 2);
    assert_eq!(r.agents[0].kind, Kind::Hermes);
    assert_eq!(r.agents[1].kind, Kind::Pi);
    assert_eq!(
        r.agents[0].secrets_path.as_deref(),
        Some("me/agents/hermes")
    );
    assert_eq!(r.agents[0].secrets_backend.as_deref(), Some("openbao"));
    assert_eq!(r.agents[1].secrets_backend, None);
    assert_eq!(r.heartbeat_kv.as_deref(), Some("me/agents/heartbeat#url"));
    assert!(r.find(Kind::Hermes).is_some());
}

#[test]
fn registry_rejects_unknown_kind() {
    assert!(Registry::parse("repo: {path: /x}\nagents:\n  - kind: skynet\n").is_err());
}

#[test]
fn kv_ref_splits_path_and_key() {
    assert_eq!(
        split_kv_ref("me/agents/heartbeat#url").expect("ok"),
        ("me/agents/heartbeat".to_string(), "url".to_string())
    );
    assert!(split_kv_ref("me/agents/heartbeat").is_err());
}

#[test]
fn env_file_parse_and_render() {
    let src = "# c\nexport A=1\nB=\"two words\"\n\nC='x=y'\nbad line\n";
    let m = parse_env(src);
    assert_eq!(m.get("A").map(String::as_str), Some("1"));
    assert_eq!(m.get("B").map(String::as_str), Some("two words"));
    assert_eq!(m.get("C").map(String::as_str), Some("x=y"));
    assert_eq!(m.len(), 3);
    let out = render_env(&m);
    assert_eq!(parse_env(&out), m);
    assert!(out.starts_with("# Generated by diegops agents"));
}

#[test]
fn timer_units_name_each_agent_explicitly() {
    let (svc, tmr) = render_units(
        std::path::Path::new("/usr/local/bin/diegops"),
        &[Kind::Hermes],
    );
    assert!(svc.contains("ExecStart=/usr/local/bin/diegops agents hermes backup"));
    assert!(svc.contains("Type=oneshot"));
    assert!(tmr.contains("OnCalendar=daily"));
    assert!(tmr.contains("Persistent=true"));
}

#[test]
fn run_state_round_trips_and_reports_age() {
    let mut s = RunState::default();
    s.record("hermes", Ok((12, 3456, "abc1234".to_string())), 1_000);
    s.record("hermes", Err("boom".to_string()), 2_000);
    let back: RunState =
        serde_json::from_str(&serde_json::to_string(&s).expect("ser")).expect("de");
    let h = back.agents.get("hermes").expect("hermes");
    assert_eq!(h.last_ok, Some(1_000));
    assert_eq!(h.last_attempt, 2_000);
    assert_eq!(h.last_error.as_deref(), Some("boom"));
    assert_eq!(h.files, 12);
    assert_eq!(h.bytes, 3456);
    assert_eq!(human_age(1_000, 1_000 + 3 * 3600 + 120), "3h2m");
    assert_eq!(human_age(0, 2 * 86_400 + 5), "2d0h");
}

#[test]
fn corrupt_run_state_warns_instead_of_silently_resetting() {
    let (s, warn) = RunState::parse("{not json", std::path::Path::new("/x/agents.json"));
    assert!(s.agents.is_empty());
    let w = warn.expect("warning");
    assert!(w.contains("/x/agents.json") && w.contains("corrupt"), "{w}");
    let (_, warn) = RunState::parse("{}", std::path::Path::new("/x"));
    assert!(warn.is_none());
}
